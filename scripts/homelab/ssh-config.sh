#!/usr/bin/env bash
# Generates SSH client config for all homelab hosts from the Ansible inventory (single source of truth)
# and includes it from ~/.ssh/config. Works over LAN or WireGuard (same private IPs).
#   scripts/homelab/ssh-config.sh            # WSL/Linux: ~/.ssh/config.d/homelab.conf
#   scripts/homelab/ssh-config.sh --windows  # additionally the Windows user's %USERPROFILE%\.ssh
set -euo pipefail
cd "$(git -C "$(dirname "$0")" rev-parse --show-toplevel)"

render() {
  ANSIBLE_CONFIG=ansible.cfg ansible-inventory -i inventories/homelab --list 2>/dev/null | python3 -c '
import json, sys
inv = json.load(sys.stdin)
print("# Generated by scripts/homelab/ssh-config.sh from inventories/homelab. Do not edit.")
for name, hv in sorted(inv["_meta"]["hostvars"].items()):
    names = " ".join([name] + hv.get("ssh_aliases", []))
    address = hv["ansible_host"]
    user = hv.get("ansible_user", "root")
    print()
    print("Host " + names)
    print("  HostName " + address)
    print("  User " + user)
    print("  ServerAliveInterval 30")
'
}

install_into() {  # $1 = .ssh directory
  local dir=$1
  mkdir -p "$dir/config.d"
  render > "$dir/config.d/homelab.conf"
  touch "$dir/config"
  if ! grep -qxF 'Include config.d/*.conf' "$dir/config"; then
    cp "$dir/config" "$dir/config.bak.$(date +%Y%m%d%H%M%S)"
    # Include must come before any Host block to apply globally.
    { echo 'Include config.d/*.conf'; echo; cat "$dir/config"; } > "$dir/config.new" && mv "$dir/config.new" "$dir/config"
  fi
  chmod 600 "$dir/config" "$dir/config.d/homelab.conf" 2>/dev/null || true
  echo "wrote $dir/config.d/homelab.conf ($(grep -c '^Host ' "$dir/config.d/homelab.conf") hosts)"
}

install_into "$HOME/.ssh"

if [[ ${1:-} == --windows ]]; then
  winprofile=$(wslpath "$(cmd.exe /c 'echo %USERPROFILE%' 2>/dev/null | tr -d '\r')")
  install_into "$winprofile/.ssh"
fi
